// Builds the paste-ready GoHighLevel snippets from src/.
//   node tools/build.mjs
// Output:
//   ghl/site-head.html        -> Website settings -> Head tracking code (once, whole site)
//   ghl/elements/*.html       -> one Custom Code element each, on the page named in the file
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const root = new URL('..', import.meta.url).pathname;
const css = readFileSync(root + 'src/vela.css', 'utf8');
const js = readFileSync(root + 'src/vela.js', 'utf8');

const head = `<!-- Vela Nox: paste into Website settings -> Head tracking code. Generated by tools/build.mjs; edit src/ instead. -->
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500&family=IBM+Plex+Sans:wght@400;500;600&display=swap" rel="stylesheet">
<style>
${css}</style>
<script>
/* One-time setup: fill these three in. Weekly changes go in the Google Sheet Settings tab, not here. */
window.VELA_CONFIG = {
  dataUrl: 'PASTE_APPS_SCRIPT_WEB_APP_URL',   // ends in /exec
  subscribeUrl: '/subscribe',                 // page with the Stripe checkout
  portalUrl: 'PASTE_CLIENT_PORTAL_LOGIN_URL'
};
${js}</script>
`;

const call = (id, fn, arg = '') =>
  `<div id="${id}"></div>\n<script>(function go(){if(window.VELA){VELA.render.${fn}('#${id}'${arg});}else{setTimeout(go,50);}})();</script>\n`;

const elements = {
  'home-this-week-strip': ['Home, directly under the hero', call('vn-strip', 'strip')],
  'home-launch-note': ['Home, "How it works", under the steps (hides itself from October 12)', call('vn-launch', 'launchNote')],
  'home-map-preview': ['Home, "The Signal Map" section', call('vn-map-preview', 'mapPreview')],
  'home-latest-track': ['Home, "Latest transmission" section', call('vn-latest', 'latest')],
  'signal-map': ['The Signal Map page, under the intro', call('vn-signal-map', 'signalMap')],
  'signal-map-broadcast-wall': ['The Signal Map page, last section (hidden until someone reaches Broadcast)', call('vn-broadcast', 'broadcastWall')],
  'tracks-index': ['Tracks & Credits page (/tracks), under the intro', call('vn-tracks', 'tracksIndex')],
  'track-page': ['Track page (/track). Renders the H1 itself: add no other H1 on this page', call('vn-track', 'track')],
  'contributors': ['Contributors page, under the intro', call('vn-contributors', 'contributors')],
  'submit-sent-confirmation': ['/sent page (the form redirects here). Renders the H1', call('vn-sent', 'confirmation')],
  'faq-vote-answer': ['Rules & FAQ, under "How does the theme vote work?"', call('vn-faq-vote', 'voteAnswer')],
  'faq-deadline-answer': ['Rules & FAQ, under "When is the deadline?"', call('vn-faq-deadline', 'deadlineAnswer')]
};

mkdirSync(root + 'ghl/elements', { recursive: true });
writeFileSync(root + 'ghl/site-head.html', head);
for (const [name, [where, html]] of Object.entries(elements)) {
  writeFileSync(root + `ghl/elements/${name}.html`, `<!-- Vela Nox custom code element. Place: ${where}. -->\n${html}`);
}
// The subscriber portal does not load the website's head code, so these two carry everything inline.
const portal = {
  'portal-submit-panel': ['Subscriber portal, "Submit" lesson. Renders the H1. Replace both FORM_ID values with the GoHighLevel form ID',
    call('vn-submit', 'submit', ", {form: 'https://api.leadconnectorhq.com/widget/form/FORM_ID', formId: 'FORM_ID'}")],
  'portal-already-sent': ['Subscriber portal, "Already sent" lesson. Renders the H1', call('vn-already', 'alreadySent')]
};
for (const [name, [where, html]] of Object.entries(portal)) {
  writeFileSync(root + `ghl/elements/${name}.html`,
    `<!-- Vela Nox custom code element. Place: ${where}. Self-contained: includes the shared script. -->\n${head.replace(/^<!--.*-->\n/, '')}${html}`);
}
console.log('Built ghl/site-head.html and', Object.keys(elements).length, 'elements');
