// Builds the paste-ready GoHighLevel snippets from src/.
//   node tools/build.mjs
// Output:
//   ghl/site-head.html        -> Website settings -> Head tracking code (once, whole site)
//   ghl/elements/*.html       -> one Custom Code element each, on the page named in the file
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const root = new URL('..', import.meta.url).pathname;
const css = readFileSync(root + 'src/vela.css', 'utf8');
const js = readFileSync(root + 'src/vela.js', 'utf8');

const head = `<!-- Vela Nox: paste into Website settings -> Head tracking code. Generated by tools/build.mjs; edit src/ instead. -->
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Big+Shoulders+Display:wght@600;800&family=Atkinson+Hyperlegible:ital,wght@0,400;0,700;1,400&display=swap" rel="stylesheet">
<style>
${css}
/* Every page, including funnel, checkout and portal pages: always night, never a white flash */
html, body { background: var(--night) !important; color: var(--mist); font-family: var(--text); }
</style>
<script>
/* One-time setup: fill these three in. Weekly changes go in the Google Sheet Settings tab, not here. */
window.VELA_CONFIG = {
  dataUrl: 'PASTE_APPS_SCRIPT_WEB_APP_URL',   // ends in /exec
  subscribeUrl: '/subscribe',                 // page with the Stripe checkout
  portalUrl: 'PASTE_CLIENT_PORTAL_LOGIN_URL'
};
${js}</script>
`;

const call = (id, fn, arg = '') =>
  `<div id="${id}"></div>\n<script>(function go(){if(window.VELA){VELA.render.${fn}('#${id}'${arg});}else{setTimeout(go,50);}})();</script>\n`;

const elements = {
  'home-this-week-strip': ['Home, directly under the hero', call('vn-strip', 'strip')],
  'home-hero-map': ['Home hero: full-width section, no padding. Put the H1, subhead and button in a text block over its lower-left (below it on phones)', call('vn-hero-map', 'heroMap')],
  'home-timeline': ['Home, "How a week works"', call('vn-timeline', 'timeline')],
  'home-launch-note': ['Home, "How a week works", under the timeline (hides itself from October 12)', call('vn-launch', 'launchNote')],
  'home-latest-track': ['Home, "Latest track" section', call('vn-latest', 'latest')],
  'signal-map': ['The Signal Map page, under the intro', call('vn-signal-map', 'signalMap')],
  'signal-map-broadcast-wall': ['The Signal Map page, last section (hidden until someone reaches Broadcast)', call('vn-broadcast', 'broadcastWall')],
  'tracks-index': ['Tracks & Credits page (/tracks), under the intro', call('vn-tracks', 'tracksIndex')],
  'track-page': ['Track page (/track). Renders the H1 itself: add no other H1 on this page', call('vn-track', 'track')],
  'contributors': ['Contributors page, under the intro', call('vn-contributors', 'contributors')],
  'submit-sent-confirmation': ['/sent page (the form redirects here). Renders the H1', call('vn-sent', 'confirmation')],
  'faq-vote-answer': ['Rules & FAQ, under "How does the theme vote work?"', call('vn-faq-vote', 'voteAnswer')],
  'section-divider': ['Top of every page section after the first: a hairline with a glowing blue tick. Same look as the preview', '<div class="vn vn-divider" role="presentation"></div>\n'],
  'faq-deadline-answer': ['Rules & FAQ, under "When is the deadline?"', call('vn-faq-deadline', 'deadlineAnswer')]
};

mkdirSync(root + 'ghl/elements', { recursive: true });
writeFileSync(root + 'ghl/site-head.html', head);
for (const [name, [where, html]] of Object.entries(elements)) {
  writeFileSync(root + `ghl/elements/${name}.html`, `<!-- Vela Nox custom code element. Place: ${where}. -->\n${html}`);
}
// The subscriber portal does not load the website's head code, so these two carry everything inline.
const portal = {
  'portal-submit-panel': ['Subscriber portal, "Submit" lesson. Renders the H1. Replace both FORM_ID values with the GoHighLevel form ID',
    call('vn-submit', 'submit', ", {form: 'https://api.leadconnectorhq.com/widget/form/FORM_ID', formId: 'FORM_ID'}")],
  'portal-already-sent': ['Subscriber portal, "Already sent" lesson. Renders the H1', call('vn-already', 'alreadySent')]
};
for (const [name, [where, html]] of Object.entries(portal)) {
  writeFileSync(root + `ghl/elements/${name}.html`,
    `<!-- Vela Nox custom code element. Place: ${where}. Self-contained: includes the shared script. -->\n${head.replace(/^<!--.*-->\n/, '')}${html}`);
}
// Legal pages: your pasted text, word for word, from copy/legal/*.txt. Only structure is added
// (title as H1, section names as H2, "- " lines as list items) and the email becomes a mailto link.
const escHtml = (t) => t.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const mail = (t) => escHtml(t).replace(/velanox@gmail\.com/g, '<a href="mailto:velanox@gmail.com">velanox@gmail.com</a>');
mkdirSync(root + 'ghl/legal', { recursive: true });
for (const name of ['terms', 'privacy', 'cancellation']) {
  const lines = readFileSync(root + `copy/legal/${name}.txt`, 'utf8').replace(/\r/g, '').split('\n');
  const out = [];
  let list = false;
  const close = () => { if (list) { out.push('</ul>'); list = false; } };
  lines.forEach((line, i) => {
    const t = line.trim();
    if (!t) { close(); return; }
    const prevBlank = i === 0 || !lines[i - 1].trim();
    const nextText = i + 1 < lines.length && lines[i + 1].trim();
    if (i === 0) out.push(`<h1>${escHtml(t)}</h1>`);
    else if (/^Last updated:/.test(t)) out.push(`<p class="vn-meta">${escHtml(t)}</p>`);
    else if (t.startsWith('- ')) { if (!list) { out.push('<ul>'); list = true; } out.push(`<li>${mail(t.slice(2))}</li>`); }
    else if (prevBlank && nextText && t.length < 60 && !/[.:;,]$/.test(t)) { close(); out.push(`<h2>${escHtml(t)}</h2>`); }
    else { close(); out.push(`<p>${mail(t)}</p>`); }
  });
  close();
  writeFileSync(root + `ghl/legal/${name}.html`,
    `<!-- Vela Nox: /${name} page body. Paste into one Custom Code element. Text is exactly as supplied in copy/legal/${name}.txt. -->\n` +
    `<style>.vn-legal{max-width:38rem}.vn-legal h1,.vn-legal h2{font-weight:700;color:var(--mist,#E7EAED)}.vn-legal h2{font-family:var(--text,'Atkinson Hyperlegible',Arial,sans-serif)}.vn-legal h1{font-family:var(--display,'Big Shoulders Display',sans-serif);font-weight:800;font-size:clamp(40px,6vw,60px);line-height:1;letter-spacing:.01em;margin:0 0 .75rem}.vn-legal h2{font-size:var(--t-body,18px);line-height:1.4;margin:2.25rem 0 .4rem}.vn-legal .vn-meta{color:var(--fog,#95A0AD);margin-bottom:2rem}.vn-legal li{margin-bottom:.4rem}</style>\n` +
    `<div class="vn vn-legal">\n${out.join('\n')}\n</div>\n`);
}
console.log('Built ghl/site-head.html and', Object.keys(elements).length, 'elements');
