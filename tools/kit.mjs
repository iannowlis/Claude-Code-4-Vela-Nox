// Builds the GoHighLevel paste-in kit in ghl/ from the same files as the preview, so the live site looks
// and behaves exactly like preview/vela-nox-preview.html:
//   ghl/1-custom-css.css     Settings -> Custom CSS (once, site-wide)
//   ghl/2-footer-code.html   Settings -> Tracking code -> Footer (once, site-wide)
//   ghl/pages/*.html         one Custom Code element per page
//   ghl/portal/*.html        the two subscriber-portal lessons (self-contained: the portal skips site code)
// Run: node tools/build.mjs && node tools/kit.mjs
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';

const root = new URL('..', import.meta.url).pathname;
const read = (p) => readFileSync(root + p, 'utf8');
const css = read('src/vela.css'), js = read('src/vela.js'), site = read('src/site.js');
const tpl = read('preview/template.html');

/* ---------- 1. Custom CSS: the site styles plus the page layout the preview uses ---------- */
const FONTS = 'https://fonts.googleapis.com/css2?family=Big+Shoulders+Display:wght@600;800&family=Atkinson+Hyperlegible:ital,wght@0,400;0,700;1,400&display=swap';
let chrome = tpl.slice(tpl.indexOf('/*{{CSS}}*/') + 11, tpl.indexOf('</style>'));
chrome = chrome
  .replace(/\/\* Preview controls: not part of the site \*\/\n(\.pv-[^\n]*\n)+/, '')
  .replace(/^\.portal-note[^\n]*\n/m, '')
  .replace('/* ---------- Page chrome for the preview (native GoHighLevel sections on the live site) ---------- */',
    '/* ---------- Page layout: header, sections, hero and page bands, footer ---------- */');
const customCss = `/* Vela Nox: paste this whole file into GoHighLevel -> Settings -> Custom CSS (once, for the whole site).
   Generated by tools/kit.mjs from src/vela.css and the preview's page layout. Edit those, not this. */
@import url('${FONTS}');

/* Always night, on every page: no white flash and no light seams between sections */
html, body { background: #070C16 !important; margin: 0; }

${css}
${chrome.trim()}
`;

/* ---------- 2. Footer code: config, the site script, the page behaviour ---------- */
const CONFIG = `window.VELA_CONFIG = {
  dataUrl: 'PASTE_APPS_SCRIPT_WEB_APP_URL',      // Apps Script web app URL, ends in /exec
  portalUrl: 'PASTE_CLIENT_PORTAL_LOGIN_URL',    // subscriber portal login
  subscribeUrl: '/subscribe'                     // the page with the Stripe order form
};`;
const footer = `<!-- Vela Nox: paste into GoHighLevel -> Settings -> Tracking code -> Footer (once, for the whole site).
     Fill in the two PASTE_ values below. Generated by tools/kit.mjs; edit src/ instead. -->
<script>
${CONFIG}
${js}
${site}</script>
`;

/* ---------- 3. Page blocks ---------- */
const logo = 'data:image/svg+xml;base64,' + readFileSync(root + 'assets/logo/vela-nox-mark.svg').toString('base64');
const PATHS = { home: '/', submit: '/submit', map: '/signal-map', tracks: '/tracks', contributors: '/contributors', rules: '/rules-faq',
  terms: '/terms', privacy: '/privacy', cancellation: '/cancellation', subscribe: '/subscribe' };
const IMAGES = new Set();
const fix = (html) => html
  .replace(/\{\{LOGO\}\}/g, logo)
  .replace(/\{\{IMG:([\w-]+)\}\}/g, (m, n) => { IMAGES.add(n); return `https://REPLACE-WITH-IMAGE-URL/${n}.webp`; })
  .replace(/href="#portal"/g, 'href="#" data-vn-portal')
  .replace(/href="#([a-z]+)"/g, (m, p) => PATHS[p] ? `href="${PATHS[p]}"` : m);

const slice = (from, to) => tpl.slice(tpl.indexOf(from), tpl.indexOf(to, tpl.indexOf(from)));
const header = slice('  <header class="site-head"', '  <main>');
const footerHtml = slice('  <footer class="site-foot">', '</div>\n\n<script>');
const pageDiv = (name) => {
  const start = tpl.indexOf(`<div class="page" data-page="${name}"`);
  const next = tpl.slice(start + 10).search(/\n\s*(<!--[^\n]*-->\n\s*)?<div class="page" data-page=|\n\s*<\/main>/);
  return tpl.slice(start, start + 10 + next).replace(/ hidden>/, '>').trimEnd();
};
const legal = (n) => read(`ghl/legal/${n}.html`).replace(/^<!--.*-->\n/, '');

const pages = [
  ['01-home', 'Home', '/', pageDiv('home')],
  ['02-submit', 'Submit (visitors who are not logged in)', '/submit', pageDiv('submit')],
  ['03-signal-map', 'Signal Map', '/signal-map', pageDiv('map')],
  ['04-tracks', 'Tracks & Credits', '/tracks', pageDiv('tracks')],
  ['05-track', 'One track (opened as /track?n=1)', '/track', pageDiv('track')],
  ['06-contributors', 'Contributors', '/contributors', pageDiv('contributors')],
  ['07-rules-faq', 'Rules & FAQ', '/rules-faq', pageDiv('rules')],
  ['08-terms', 'Terms of Service', '/terms', `<div class="page" data-page="terms"><section class="wrap">${legal('terms')}</section></div>`],
  ['09-privacy', 'Privacy Policy', '/privacy', `<div class="page" data-page="privacy"><section class="wrap">${legal('privacy')}</section></div>`],
  ['10-cancellation', 'Cancellation Policy', '/cancellation', `<div class="page" data-page="cancellation"><section class="wrap">${legal('cancellation')}</section></div>`],
  ['11-sent', 'Sent (the submission form redirects here)', '/sent',
    `<div class="page" data-page="sent">\n      <section class="wrap sent-bg" style="--img:url({{IMG:strands-texture}})"><div id="vn-sent"></div></section>\n    </div>`]
];
rmSync(root + 'ghl/pages', { recursive: true, force: true });
rmSync(root + 'ghl/portal', { recursive: true, force: true });
rmSync(root + 'ghl/elements', { recursive: true, force: true });
rmSync(root + 'ghl/site-head.html', { force: true });
mkdirSync(root + 'ghl/pages', { recursive: true });
mkdirSync(root + 'ghl/portal', { recursive: true });
const note = (title, path) => `<!-- Vela Nox · ${title} · page URL ${path}
     Paste this whole file into ONE Custom Code element. Put it in a full-width section with no padding
     (section, row and column padding 0, width full). Nothing else goes on the page. -->\n`;
for (const [file, title, path, body] of pages) {
  writeFileSync(root + `ghl/pages/${file}.html`,
    note(title, path) + fix(`<div class="vn" id="top">\n${header}  <main>\n    ${body}\n  </main>\n\n${footerHtml}</div>\n`));
}
// For pages GoHighLevel builds itself (the /subscribe order form): the same header and footer on their own
writeFileSync(root + 'ghl/pages/12-header-only.html', `<!-- Vela Nox · header for a native GoHighLevel page (/subscribe). One Custom Code element at the very top. -->\n` +
  fix(`<div class="vn">\n${header.replace(/<div class="menu"/, '<div class="menu"')}</div>\n`));
writeFileSync(root + 'ghl/pages/13-footer-only.html', `<!-- Vela Nox · footer for a native GoHighLevel page (/subscribe). One Custom Code element at the very bottom. -->\n` +
  fix(`<div class="vn">\n${footerHtml}</div>\n`));

/* ---------- 4. Portal lessons: they don't load the site's CSS or footer code, so each carries its own ---------- */
const self = `<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="${FONTS}" rel="stylesheet">
<style>
${css}html, body { background: #070C16 !important; color: #E6EDF5; }
</style>
<script>
${CONFIG}
${js}</script>
`;
const call = (id, fn, arg = '') => `<div class="vn"><div id="${id}"></div></div>\n<script>(function go(){if(window.VELA){VELA.render.${fn}('#${id}'${arg});}else{setTimeout(go,50);}})();</script>\n`;
writeFileSync(root + 'ghl/portal/portal-submit-panel.html',
  `<!-- Vela Nox · subscriber portal, "Submit" lesson. One Custom Code element. Fill in the two PASTE_ values and replace both FORM_ID values with the GoHighLevel form ID. -->\n` +
  self + call('vn-submit', 'submit', ", {form: 'https://api.leadconnectorhq.com/widget/form/FORM_ID', formId: 'FORM_ID'}"));
writeFileSync(root + 'ghl/portal/portal-already-sent.html',
  `<!-- Vela Nox · subscriber portal, "Already sent" lesson. One Custom Code element. Fill in the two PASTE_ values. -->\n` +
  self + call('vn-already', 'alreadySent'));

writeFileSync(root + 'ghl/1-custom-css.css', customCss);
writeFileSync(root + 'ghl/2-footer-code.html', footer);
writeFileSync(root + 'ghl/images.txt', [...IMAGES].sort().map((n) => `assets/${n}.webp`).join('\n') + '\n');
console.log('Built ghl/ kit:', pages.length, 'pages, images:', [...IMAGES].sort().join(', '),
  '| css', Math.round(customCss.length / 1024) + 'KB | footer', Math.round(footer.length / 1024) + 'KB');
